  function resolveLanguage(language) { return /^zh(?:-|$)/i.test(language || '') ? 'zh-CN' : 'en'; }
  function createTranslator(language) {
    const chinese = resolveLanguage(language) === 'zh-CN';
    return function translate(message, ...values) {
      const key = Array.isArray(message) ? message.map((part,i)=>part+(i<message.length-1?`{${i}}`:'')).join('') : message;
      const template = chinese ? key : (Object.prototype.hasOwnProperty.call(english,key) ? english[key] : key);
      return template.replace(/\{(\d+)\}/g,(match,index)=>Number(index)<values.length ? String(values[Number(index)]) : match);
    };
  }
  let translator=createTranslator('en');
